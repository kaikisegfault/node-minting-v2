/**
 * Deploys all 3 contracts to a running local Hardhat node.
 * Outputs contract addresses and env vars for Lambda local testing.
 *
 * Usage:
 *   Terminal 1: npx hardhat node                          (starts chain on :8545)
 *   Terminal 2: npx hardhat run scripts/deploy-local.ts --network localhost
 */

import { ethers } from "hardhat";
import * as dotenv from "dotenv";
import * as fs from "fs";
import path from "path";

dotenv.config({ path: path.resolve(__dirname, "../../.env") });

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log(`Deploying with: ${deployer.address}`);

  // Use signer from env or default Hardhat account
  const signerKey = process.env.SIGNER_PRIVATE_KEY || "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";
  const signerWallet = new ethers.Wallet(signerKey);
  const signerPublicKey = signerWallet.address;

  // Deploy "ETH chain" contracts (non-whitelist)
  console.log("\n--- Deploying 'ETH' contracts (non-whitelist) ---");
  const EthNodes = await ethers.getContractFactory("explorills_Nodes");
  const ethNodes = await EthNodes.deploy(false, signerPublicKey, deployer.address, "");
  await ethNodes.waitForDeployment();
  const ethNodesAddr = await ethNodes.getAddress();

  const EthEscrow = await ethers.getContractFactory("explorills_NodeEscrow");
  const ethEscrow = await EthEscrow.deploy();
  await ethEscrow.waitForDeployment();

  const EthBridge = await ethers.getContractFactory("explorills_BridgeEscrow");
  const ethBridge = await EthBridge.deploy();
  await ethBridge.waitForDeployment();

  await (await ethNodes.setOneTimeNodeEscrow(await ethEscrow.getAddress())).wait();
  await (await ethNodes.setOneTimeCrossChainEscrow(await ethBridge.getAddress())).wait();
  await (await ethNodes.setPaused(false)).wait();
  console.log(`  Nodes:  ${ethNodesAddr}`);

  // Deploy "Flare chain" contracts (whitelist)
  console.log("\n--- Deploying 'Flare' contracts (whitelist) ---");
  const FlareNodes = await ethers.getContractFactory("explorills_Nodes");
  const flareNodes = await FlareNodes.deploy(true, signerPublicKey, deployer.address, "");
  await flareNodes.waitForDeployment();
  const flareNodesAddr = await flareNodes.getAddress();

  const FlareEscrow = await ethers.getContractFactory("explorills_NodeEscrow");
  const flareEscrow = await FlareEscrow.deploy();
  await flareEscrow.waitForDeployment();

  const FlareBridge = await ethers.getContractFactory("explorills_BridgeEscrow");
  const flareBridge = await FlareBridge.deploy();
  await flareBridge.waitForDeployment();

  await (await flareNodes.setOneTimeNodeEscrow(await flareEscrow.getAddress())).wait();
  await (await flareNodes.setOneTimeCrossChainEscrow(await flareBridge.getAddress())).wait();
  await (await flareNodes.setPaused(false)).wait();
  console.log(`  Nodes:  ${flareNodesAddr}`);

  // Deploy "BSC chain" contracts (non-whitelist)
  console.log("\n--- Deploying 'BSC' contracts (non-whitelist) ---");
  const BscNodes = await ethers.getContractFactory("explorills_Nodes");
  const bscNodes = await BscNodes.deploy(false, signerPublicKey, deployer.address, "");
  await bscNodes.waitForDeployment();
  const bscNodesAddr = await bscNodes.getAddress();

  const BscEscrow = await ethers.getContractFactory("explorills_NodeEscrow");
  const bscEscrow = await BscEscrow.deploy();
  await bscEscrow.waitForDeployment();

  const BscBridge = await ethers.getContractFactory("explorills_BridgeEscrow");
  const bscBridge = await BscBridge.deploy();
  await bscBridge.waitForDeployment();

  await (await bscNodes.setOneTimeNodeEscrow(await bscEscrow.getAddress())).wait();
  await (await bscNodes.setOneTimeCrossChainEscrow(await bscBridge.getAddress())).wait();
  await (await bscNodes.setPaused(false)).wait();
  console.log(`  Nodes:  ${bscNodesAddr}`);

  // Write .env.local for Lambda
  const envLocalContent = `# Auto-generated by deploy-local.ts — do not commit
LOCAL_MODE=true
SIGNER_PRIVATE_KEY=${signerKey}

# All 3 "chains" running on same Hardhat node, different contract addresses
ETH_RPC_URL=http://127.0.0.1:8545
FLARE_RPC_URL=http://127.0.0.1:8545
BSC_RPC_URL=http://127.0.0.1:8545

ETH_CONTRACT_ADDRESS=${ethNodesAddr}
FLARE_CONTRACT_ADDRESS=${flareNodesAddr}
BSC_CONTRACT_ADDRESS=${bscNodesAddr}

MOCK_ETH_PRICE=3000
MOCK_FLR_PRICE=0.02
MOCK_BNB_PRICE=600

LAMBDA_LOCAL_PORT=3001
`;

  const envPath = path.resolve(__dirname, "../../.env.local");
  fs.writeFileSync(envPath, envLocalContent);
  console.log(`\nWrote ${envPath}`);

  console.log("\n=== Local Deployment Summary ===");
  console.log(`ETH Nodes:   ${ethNodesAddr}`);
  console.log(`Flare Nodes: ${flareNodesAddr}`);
  console.log(`BSC Nodes:   ${bscNodesAddr}`);
  console.log(`Signer:      ${signerPublicKey}`);
  console.log(`\nNext: update Lambda .env with these addresses and run local-server.mjs`);
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
